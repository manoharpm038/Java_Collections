package com.set.abstractset.hashset;

public class HashConcept {

	public static void main(String[] args) {
		/*
		 1. Concept of HashSet

	HashSet is a part of Java Collections Framework and implements the Set interface.
	
	Set means:
	
	It does not allow duplicate elements.
	It does not maintain any order of elements (not insertion-order, not sorted).
	HashSet allows one null element.
	It is faster for operations like add, remove, and search because it uses hashing internally.
	
	3. Features of HashSet

	No duplicates allowed
	
	Automatically ignores duplicates using equals() and hashCode().
	
	Allows null element
	
	Only one null is allowed.
	
	Fast operations
	
	O(1) average time complexity for add, remove, and contains.
	
	Iterators
	
	Iterator and enhanced for loop can traverse elements.
	
	Implements Set interface
	
	So supports all Set operations: add, remove, contains, size, clear.
	
	Common Operations 		/ Methods
	Method					Description
	add(E e)				Adds an element. Returns true if added, false if duplicate.
	remove(Object o)		Removes the element if present.
	contains(Object o)		Checks if element exists. Returns true/false.
	size()					Returns the number of elements.
	isEmpty()				Checks if the HashSet is empty.
	clear()					Removes all elements.
	iterator()				Returns an iterator to traverse elements.
	clone()					Returns a shallow copy of the HashSet.
	toArray()				Converts the HashSet to an array.
		 */

	}

}
